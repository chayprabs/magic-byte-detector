#!/usr/bin/env node
/** Generate minimal magic-byte fixture files from signature table */
import { writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outDir = join(__dirname, "../fixtures/corpus");

const fixtures = [
  ["pdf.bin", [0x25, 0x50, 0x44, 0x46, 0x2d]],
  ["zip.bin", [0x50, 0x4b, 0x03, 0x04]],
  ["png.bin", [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]],
  ["jpg.bin", [0xff, 0xd8, 0xff, 0xe0]],
  ["gif.bin", [0x47, 0x49, 0x46, 0x38, 0x39, 0x61]],
  ["exe.bin", [0x4d, 0x5a, 0x90, 0x00]],
  ["elf.bin", [0x7f, 0x45, 0x4c, 0x46]],
  ["gzip.bin", [0x1f, 0x8b, 0x08]],
  ["bz2.bin", [0x42, 0x5a, 0x68]],
  ["7z.bin", [0x37, 0x7a, 0xbc, 0xaf, 0x27, 0x1c]],
  ["rar.bin", [0x52, 0x61, 0x72, 0x21, 0x1a, 0x07]],
  ["ole.bin", [0xd0, 0xcf, 0x11, 0xe0, 0xa1, 0xb1, 0x1a, 0xe1]],
  ["wasm.bin", [0x00, 0x61, 0x73, 0x6d]],
  ["mp3.bin", [0x49, 0x44, 0x33]],
  ["wav.bin", [0x52, 0x49, 0x46, 0x46, 0, 0, 0, 0, 0x57, 0x41, 0x56, 0x45]],
  ["ogg.bin", [0x4f, 0x67, 0x67, 0x53]],
  ["sqlite.bin", [0x53, 0x51, 0x4c, 0x69, 0x74, 0x65, 0x20, 0x66, 0x6f, 0x72, 0x6d, 0x61, 0x74]],
  ["woff.bin", [0x77, 0x4f, 0x46, 0x46]],
  ["rtf.bin", [0x7b, 0x5c, 0x72, 0x74, 0x66]],
  ["polyglot-pdf-zip.bin", [0x25, 0x50, 0x44, 0x46, 0x50, 0x4b, 0x03, 0x04]],
];

mkdirSync(outDir, { recursive: true });
for (const [name, bytes] of fixtures) {
  writeFileSync(join(outDir, name), Buffer.from(bytes));
}
console.log(`Wrote ${fixtures.length} fixtures to ${outDir}`);
